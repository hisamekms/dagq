-- dagq-postgres-base: 94
-- The base of the Postgres series (ADR-t3986-1 decision 7): one file that
-- makes the schema the SQLite series has at the version on the first line,
-- which is the version it records. Each SQLite migration after that version
-- has a file here under the same name; build.rs refuses a missing or an
-- unmatched one. A migration is named here by its name and never by its
-- number, so renumbering one on landing moves nothing
-- in this directory.
--
-- How the types are carried over from SQLite:
--
-- INTEGER             bigint. The one exception is write_leader.singleton,
--                     always 1, as integer.
-- AUTOINCREMENT, and  bigint GENERATED BY DEFAULT AS IDENTITY: BY DEFAULT so
-- an INTEGER PRIMARY  an import keeps its IDs. plan_requests, spike_cycles,
-- KEY the insert      replan_operations and task_holds have no AUTOINCREMENT
-- leaves out          but take their IDs from the same rowid rule.
-- REAL                double precision, never an integer or numeric:
--                     node_samples, session_resources, run_resources and
--                     supervisors.max_load, the columns the migrations
--                     node_samples, session_owners_and_resources,
--                     environment_resources, node_sample_held_targets and
--                     supervisor_claim_spacing added.
-- JSON held as TEXT   jsonb, for what json_extract and json_each read and
--                     every other column only ever written as a JSON
--                     document. replan_plans.plan stays text: its hash is
--                     of the bytes written, which jsonb would not keep.
-- 0 and 1             boolean, for the eight columns that hold a truth value:
--                     asks.answer_approval, supervisors.auto_update and
--                     handoff_accepted, session_steps.background,
--                     ledger_rows.final and legacy, run_resources.is_last,
--                     tasks.wait_for_build.
-- dates held as TEXT  text, compared as the shared SQL compares them.
-- a primary key with  NOT NULL columns and a partial unique index: only
-- a column that can   replan_mappings, whose child_task_id is NULL for a
-- be NULL             condition no child takes.
-- the rowid order     the column seq (identity, NOT NULL, unique) on task_runs
--                     and supervisors, the two tables SQLite reads in rowid
--                     order: a table here has no rowid to order by.
--
-- The defaults read the clock as the dialect does
-- (src/infrastructure/sql_dialect.rs), clock_timestamp() and not the
-- transaction's start. The two indexes on run_events' JSON use the dialect's
-- expressions, so the store's statements can use them.
--
-- No trigger (decision 6): the adapter's writes hold what they do in SQLite.
-- No constraint on values (ADR-t876-1). Not carried over: schema_floor, which
-- dagq_schema replaces, and the FTS5 table's own tables. search_index here is
-- a plain table of the same columns with the rowid SQLite's triggers give
-- each row; which index it gets, if any, is for the Postgres search to decide.

-- The schema's version and floor, one row (SQLite's user_version and
-- schema_floor). The adapter inserts it with the version on the first line.
-- version  the migrations applied, in SQLite's count.
-- floor    binaries that know an older schema are refused.
CREATE TABLE dagq_schema (
  version bigint NOT NULL,
  floor bigint NOT NULL
);
CREATE UNIQUE INDEX dagq_schema_one_row ON dagq_schema((1));

